# -*- coding: utf-8 -*-
r"""
make_overleaf_bundle.py

Builds a self-contained Overleaf project from the assembled submission.

main.tex reads its 23 section bodies and tables out of ../writing/, which is
a sibling of world_development_submission/. That is fine locally and cannot
work on Overleaf: Overleaf compiles inside the project root and will not
follow ".." out of it, so the include fails with

    LaTeX Error: File `../writing/abstract_draft.tex' not found.

no matter how the files are arranged in the project. The fix is to bring the
drafts inside the project and point \draftdir at them, which is the one line
that differs between the local build and the Overleaf one.

What the bundle contains:

    main.tex              \draftdir overridden to writing/
    supplementary.tex     (already standalone)
    highlights.tex
    references.bib
    figures/              only the figures main.tex actually uses
    writing/              only the drafts and tables it actually includes

Only referenced files are copied, so stale figures from earlier versions
cannot travel to Overleaf and be picked up by accident.

Line endings are normalised to LF in the bundle. The repository files are
CRLF, which is why the Overleaf log shows a trailing ^^M on the error line;
it is cosmetic but it makes logs harder to read.

Usage:
    python pipeline/make_overleaf_bundle.py
    -> world_development_submission/overleaf_bundle/
    -> world_development_submission/overleaf_bundle.zip   (upload this)
"""

import os
import re
import shutil
import time
import zipfile

SUB = "world_development_submission"
WRITING = "writing"
OUT = os.path.join(SUB, "overleaf_bundle")
ZIP = os.path.join(SUB, "overleaf_bundle.zip")
SINGLE = os.path.join(SUB, "overleaf_single_main.tex")

# highlights_submission.tex is the wrapper that actually renders the
# bullets; highlights.tex alone is a bare itemize fragment that nothing
# compiles. Without the wrapper the Highlights page, which World
# Development requires as a separate upload, could not be built on Overleaf.
ROOT_FILES = ["main.tex", "supplementary.tex", "highlights.tex",
              "highlights_submission.tex", "references.bib"]

DRAFT = re.compile(r"\\draft\{([^}]+)\}")
TBL = re.compile(r"\\tbl\{([^}]+)\}")
GRAPHIC = re.compile(r"\\includegraphics(?:\[[^\]]*\])?%?\s*\{([^}]+)\}")


def write_lf(path, text):
    """Write with LF endings; Overleaf logs are cleaner without ^^M."""
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text.replace("\r\n", "\n"))


def build_single_file(main_src, drafts, tables):
    r"""Expand every \draft and \tbl inline and return one standalone file.

    For the case where the Overleaf project belongs to someone else: there
    is nothing to upload and no folders to create, only main.tex to replace.
    The trade-off is that the result is a build artifact, so prose edits
    made in Overleaf are overwritten the next time this runs. Whoever owns
    the workflow has to decide which copy is the source of truth.
    """
    def read(path, label):
        body = open(path, encoding="utf-8", newline="").read()
        body = body.replace("\r\n", "\n").strip("\n")
        bar = "% " + "-" * 68
        return (f"{bar}\n% BEGIN {label}  (generated from {path})\n{bar}\n"
                f"{body}\n{bar}\n% END {label}\n{bar}\n")

    out = main_src.replace("\r\n", "\n")

    for name in drafts:
        out = out.replace("\\draft{" + name + "}",
                          read(os.path.join(WRITING, name + ".tex"), name))
    for name in tables:
        out = out.replace("\\tbl{" + name + "}",
                          read(os.path.join(WRITING, "tables", name + ".tex"),
                               name))

    # The include machinery is now dead. Drop it, but only after proving
    # nothing still needs it, or the paste would fail on Overleaf exactly
    # the way the original did.
    assert "\\draft{" not in out and "\\tbl{" not in out, \
        "an include survived expansion; the single file would not compile"
    for line in (r"\providecommand{\draftdir}{../writing/}",
                 r"\providecommand{\draft}[1]{\input{\draftdir #1}}",
                 r"\providecommand{\tbl}[1]{\input{\draftdir tables/#1}}"):
        out = out.replace(line + "\n", "")

    # The assembled-document notice describes a file that includes its
    # sections. This one does not, and the notice is the first thing a
    # reader sees, so replace it rather than leave it contradicting the
    # banner directly above it.
    out = out.replace(
        "% This document is ASSEMBLED, not hand-maintained. Section bodies "
        "live in\n"
        "% ../writing/*.tex and tables in ../writing/tables/*.tex, and both "
        "are\n"
        "% regenerated by the pipeline:\n",
        "% This is the single-file build: the section bodies and tables are\n"
        "% expanded inline below. They are generated by the pipeline:\n")

    # The include macros were stripped above, leaving \makeatletter wrapped
    # around a lone comment about a mechanism this file does not use.
    lines = out.split("\n")
    try:
        i = lines.index("% Section bodies are kept in ../writing/ so the "
                        "pipeline can rewrite them.")
        j = lines.index("\\makeatother", i)
        del lines[i:j + 1]
        out = "\n".join(lines)
    except ValueError:
        pass  # already absent; nothing to clean

    banner = (
        "% ====================================================================\n"
        "% SINGLE-FILE BUILD. Generated by pipeline/make_overleaf_bundle.py.\n"
        "%\n"
        "% Every section body and table is expanded inline here, so this file\n"
        "% compiles on its own with no ../writing/ include and nothing to\n"
        "% upload but the figures.\n"
        "%\n"
        "% Edits made inside this file are LOST when it is regenerated. Make\n"
        "% them in writing/*.tex and writing/tables/*.tex and re-run, or agree\n"
        "% that the Overleaf copy is now the source of truth and stop\n"
        "% regenerating. Do not do both.\n"
        "% ====================================================================\n")
    return banner + out

def clear_output_dir():
    """Remove the previous bundle, tolerating OneDrive's file locks.

    The repository sits under OneDrive, which keeps directory handles open
    while syncing, so rmtree intermittently fails with WinError 5 on a
    rebuild that is otherwise fine. The handle is released within about a
    second, so a short retry is enough.
    """
    if not os.path.exists(OUT):
        return
    for attempt in range(5):
        try:
            shutil.rmtree(OUT)
            return
        except PermissionError:
            if attempt == 4:
                raise
            time.sleep(0.6)


def main():
    clear_output_dir()
    os.makedirs(OUT)

    main_src = open(os.path.join(SUB, "main.tex"),
                    encoding="utf-8", newline="").read()

    # The one substantive change. Assert rather than silently no-op: if the
    # macro block is ever edited back to a literal path, the bundle would
    # ship broken and only fail once it reached Overleaf.
    old = r"\providecommand{\draftdir}{../writing/}"
    new = r"\providecommand{\draftdir}{writing/}"
    assert main_src.count(old) == 1, (
        "main.tex does not define \\draftdir as expected; the bundle would "
        "not compile on Overleaf. Check the \\makeatletter block.")
    write_lf(os.path.join(OUT, "main.tex"), main_src.replace(old, new))

    for f in ROOT_FILES[1:]:
        p = os.path.join(SUB, f)
        if os.path.exists(p):
            write_lf(os.path.join(OUT, f),
                     open(p, encoding="utf-8", newline="").read())

    # Copy only what main.tex actually includes.
    drafts = DRAFT.findall(main_src)
    tables = TBL.findall(main_src)
    for name in drafts:
        src = os.path.join(WRITING, name + ".tex")
        write_lf(os.path.join(OUT, "writing", name + ".tex"),
                 open(src, encoding="utf-8", newline="").read())
    for name in tables:
        src = os.path.join(WRITING, "tables", name + ".tex")
        write_lf(os.path.join(OUT, "writing", "tables", name + ".tex"),
                 open(src, encoding="utf-8", newline="").read())

    # Copy only referenced figures, so superseded ones cannot travel along.
    figs = set()
    for tex in [main_src] + [open(os.path.join(SUB, f), encoding="utf-8").read()
                             for f in ROOT_FILES[1:]
                             if os.path.exists(os.path.join(SUB, f))
                             and f.endswith(".tex")]:
        figs |= {g.strip() for g in GRAPHIC.findall(tex)}
    for g in sorted(figs):
        src = os.path.join(SUB, g)
        dst = os.path.join(OUT, g)
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        shutil.copy2(src, dst)

    # Second output: one standalone file, for a project you cannot upload to.
    single = build_single_file(main_src, drafts, tables)
    write_lf(SINGLE, single)

    with zipfile.ZipFile(ZIP, "w", zipfile.ZIP_DEFLATED) as z:
        for base, _, names in os.walk(OUT):
            for n in names:
                full = os.path.join(base, n)
                z.write(full, os.path.relpath(full, OUT))

    n_files = sum(len(f) for _, _, f in os.walk(OUT))
    size = os.path.getsize(ZIP) / 1e6
    print(f"bundle -> {OUT}")
    print(f"  {len(drafts)} drafts, {len(tables)} tables, {len(figs)} figures")
    for g in sorted(figs):
        print(f"    {g}")
    print(f"  draftdir overridden to writing/")
    print(f"\nzip -> {ZIP}  ({n_files} files, {size:.1f} MB)")
    n_lines = single.count("\n") + 1
    print(f"\nsingle file -> {SINGLE}  ({n_lines:,} lines, all includes "
          f"expanded)")
    print("\nTwo ways to get this onto Overleaf:")
    print("  own the project      -> upload overleaf_bundle.zip "
          "(New Project > Upload Project)")
    print("  collaborator only    -> paste overleaf_single_main.tex over "
          "main.tex, re-upload the 3 figures")


if __name__ == "__main__":
    main()
