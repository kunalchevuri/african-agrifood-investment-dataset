# -*- coding: utf-8 -*-
"""Every numeric claim in the drafts must appear in the regenerated outputs.

A claim counts as accounted for if it matches the pool exactly, or if it is
the correctly-rounded form of a pooled value (the prose rounds 0.8006 to
0.801 and 26.26 to 26.3, which is legitimate but must still be checked).
"""
import glob
import os
import re

fin = open("verified_findings/00_FINDINGS_SUMMARY.md", encoding="utf-8").read()
tabs = "".join(open(f, encoding="utf-8").read()
               for f in glob.glob("writing/tables/*.tex"))
# The 2015 start date is justified against pre-window disclosure, which
# the standard run cannot produce because it drops those rows. That
# comparison is regenerated by pipeline/window_check.py.
win = open("verified_findings/16_window_disclosure.csv",
           encoding="utf-8").read()
# supplementary S4 is regenerated from the stage-composition CSV, so that
# file belongs in the pool too.
stg = open("verified_findings/15_stage_composition.csv",
           encoding="utf-8").read()
# S4's disclosure table and panel counts, and S5's centrality-volume
# correlations, are typed from these three files.
extra = "".join(open(f"verified_findings/{n}", encoding="utf-8").read()
                for n in ("17_disclosure_by_stream.csv",
                          "18_did_feasibility.csv",
                          "19b_dfi_centrality_volume_correlations.csv",
                          "20_investor_histories.csv",
                          "21_dfi_instrument_mix.csv"))
pool = fin + tabs + win + stg + extra
poolflat = pool.replace(",", "")

# every numeric literal in the pool, for the rounding check
POOL_NUMS = set()
for tok in re.findall(r"[0-9]+(?:\.[0-9]+)?", pool.replace(",", "")):
    POOL_NUMS.add(tok)


def rounds_to(claim):
    """True if some pooled number rounds to `claim` at the claim's precision."""
    if "." not in claim:
        try:
            c = float(claim)
        except ValueError:
            return False
        return any(abs(round(float(p)) - c) < 1e-9
                   for p in POOL_NUMS if _num(p) is not None)
    dp = len(claim.split(".")[1])
    try:
        c = float(claim)
    except ValueError:
        return False
    for p in POOL_NUMS:
        v = _num(p)
        if v is not None and abs(round(v, dp) - c) < 1e-9:
            return True
    return False


def _num(s):
    try:
        return float(s)
    except ValueError:
        return None


# years, citation years, section numbers, and figures quoted from the prior
# published version rather than regenerated
CTX = set("""2010 2014 2015 2016 2017 2018 2019 2020 2021 2022 2023 2024 2025
2026 1947 1959 1972 1977 1979 1987 1988 1991 1992 1998 2000 2001 2002 2007
2008 2011 2012 2013 26 131 347 1 2
3 4 5 8 10 12 16 21 27 40 43 48 56 60 68 90 119 359""".split())
PRIOR = {"0.901", "0.006", "0.003", "100"}   # quoted from the NEUDC version
# Figures taken from a cited source rather than produced by our pipeline.
# 87.9: MDB/DFI private-finance mobilization to low- and middle-income
# countries in 2023, checked against the IFC joint-report page for
# mdbdfi2025. The all-income-group total on that page is 220.1, and the
# paper deliberately quotes the low- and middle-income figure instead.
EXTERNAL = {"87.9"}

tot = miss = rnd = 0
# main.tex carries the figure captions and supplementary.tex the S-tables;
# both state numbers and neither was being scanned.
TARGETS = (sorted(glob.glob("writing/*.tex"))
           + ["world_development_submission/main.tex",
              "world_development_submission/supplementary.tex"])
for f in TARGETS:
    s = re.sub(r"(?m)^%.*", "", open(f, encoding="utf-8").read())
    # LaTeX thousands separator: 1{,}640 is one number, not "1" and "640"
    s = s.replace("{,}", ",")
    s = re.sub(r"\S+@\S+", " ", s)              # author emails
    s = re.sub(r"\\cite[a-z]*\{[^}]*\}", " ", s)   # citation keys
    s = re.sub(r"\\includegraphics\[[^\]]*\]", " ", s)  # figure sizes
    # DOIs and URLs: an identifier, not a measurement. Without this the
    # deposit DOI reads as the unverified claims "10.5281" and "23500117".
    s = re.sub(r"\\url\{[^}]*\}", " ", s)
    s = re.sub(r"\b(?:doi:|https?://)\S+", " ", s)
    seen, bad, soft = set(), [], []
    for n in re.findall(r"([0-9]+(?:[.,][0-9]+)*)", s):
        if n in seen or n in CTX or n in PRIOR or n in EXTERNAL:
            continue
        seen.add(n)
        if n in pool or n.replace(",", "") in poolflat:
            continue
        if rounds_to(n.replace(",", "")):
            soft.append(n)
            continue
        bad.append(n)
    tot += len(seen)
    miss += len(bad)
    rnd += len(soft)
    note = f"{len(bad)} unverified {bad if bad else ''}"
    if soft:
        note += f"   [{len(soft)} rounded: {soft}]"
    print(f"  {os.path.basename(f):24s} {len(seen):3d} numbers, {note}")

print(f"\n  {tot} distinct numbers checked")
print(f"  {miss} unaccounted for, {rnd} accounted for as correct rounding")
print("  (values quoted from the submitted version are listed as PRIOR "
      "and checked by hand against it)")
